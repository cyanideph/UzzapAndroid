create table if not exists public.blocked_users (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  blocked_username text not null,
  created_at timestamptz not null default now(),
  unique(owner_id, blocked_username)
);
alter table public.blocked_users enable row level security;
do $$ begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='blocked_users' and policyname='blocked_users_read_own') then create policy blocked_users_read_own on public.blocked_users for select using (owner_id = auth.uid()); end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='blocked_users' and policyname='blocked_users_insert_own') then create policy blocked_users_insert_own on public.blocked_users for insert with check (owner_id = auth.uid()); end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='blocked_users' and policyname='blocked_users_delete_own') then create policy blocked_users_delete_own on public.blocked_users for delete using (owner_id = auth.uid()); end if;
end $$;

