end $$;

create or replace function public.touch_my_presence(p_is_online boolean default true)
returns void language sql security definer set search_path = public
as $$ update public.profiles set is_online=p_is_online,last_seen=now() where owner_id=auth.uid(); $$;
revoke all on function public.touch_my_presence(boolean) from public;
grant execute on function public.touch_my_presence(boolean) to authenticated;
create index if not exists profiles_online_last_seen_idx on public.profiles (is_online,last_seen desc);

