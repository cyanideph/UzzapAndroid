-- Uzzap presence, unread PM state, blocking and reporting.

ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS last_seen TIMESTAMPTZ DEFAULT now();
CREATE INDEX IF NOT EXISTS idx_profiles_presence ON public.profiles(username, is_online, last_seen DESC);

ALTER TABLE public.direct_messages ADD COLUMN IF NOT EXISTS read_at TIMESTAMPTZ;
CREATE INDEX IF NOT EXISTS idx_dm_unread ON public.direct_messages(recipient_id, read_at, created_at DESC);

CREATE TABLE IF NOT EXISTS public.blocked_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  blocked_username TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(owner_id, blocked_username)
);
CREATE TABLE IF NOT EXISTS public.user_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  reported_username TEXT NOT NULL,
  reason TEXT NOT NULL,
  details TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION public.set_safety_owner()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Authentication required'; END IF;
  IF TG_TABLE_NAME = 'blocked_users' THEN NEW.owner_id := auth.uid(); END IF;
  IF TG_TABLE_NAME = 'user_reports' THEN NEW.reporter_id := auth.uid(); END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_blocked_users_owner ON public.blocked_users;
CREATE TRIGGER trg_blocked_users_owner BEFORE INSERT ON public.blocked_users FOR EACH ROW EXECUTE FUNCTION public.set_safety_owner();
DROP TRIGGER IF EXISTS trg_user_reports_owner ON public.user_reports;
CREATE TRIGGER trg_user_reports_owner BEFORE INSERT ON public.user_reports FOR EACH ROW EXECUTE FUNCTION public.set_safety_owner();

CREATE OR REPLACE FUNCTION public.prevent_blocked_direct_message()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM public.blocked_users b
    JOIN public.profiles p ON p.username = b.blocked_username
    WHERE b.owner_id = NEW.recipient_id AND p.owner_id = auth.uid()
  ) THEN
    RAISE EXCEPTION 'Direct messaging is blocked by the recipient';
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_prevent_blocked_dm ON public.direct_messages;
CREATE TRIGGER trg_prevent_blocked_dm BEFORE INSERT ON public.direct_messages FOR EACH ROW EXECUTE FUNCTION public.prevent_blocked_direct_message();

ALTER TABLE public.blocked_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_reports ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS blocked_users_read_own ON public.blocked_users;
DROP POLICY IF EXISTS blocked_users_insert_own ON public.blocked_users;
DROP POLICY IF EXISTS blocked_users_delete_own ON public.blocked_users;
CREATE POLICY blocked_users_read_own ON public.blocked_users FOR SELECT TO authenticated USING (owner_id = auth.uid());
CREATE POLICY blocked_users_insert_own ON public.blocked_users FOR INSERT TO authenticated WITH CHECK (owner_id = auth.uid());
CREATE POLICY blocked_users_delete_own ON public.blocked_users FOR DELETE TO authenticated USING (owner_id = auth.uid());
DROP POLICY IF EXISTS user_reports_insert_own ON public.user_reports;
DROP POLICY IF EXISTS user_reports_read_own ON public.user_reports;
CREATE POLICY user_reports_insert_own ON public.user_reports FOR INSERT TO authenticated WITH CHECK (reporter_id = auth.uid());
CREATE POLICY user_reports_read_own ON public.user_reports FOR SELECT TO authenticated USING (reporter_id = auth.uid());

DROP POLICY IF EXISTS dm_update_recipient ON public.direct_messages;
CREATE POLICY dm_update_recipient ON public.direct_messages FOR UPDATE TO authenticated USING (recipient_id = auth.uid()) WITH CHECK (recipient_id = auth.uid());

CREATE OR REPLACE FUNCTION public.touch_my_presence(p_is_online BOOLEAN)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  UPDATE public.profiles SET is_online = p_is_online, last_seen = now() WHERE owner_id = auth.uid();
END;
$$;
REVOKE ALL ON FUNCTION public.touch_my_presence(BOOLEAN) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.touch_my_presence(BOOLEAN) TO authenticated;

DO $$ BEGIN
