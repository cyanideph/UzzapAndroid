-- Room invitations for legacy-Uzzap parity.
-- Safe additive migration: does not remove or rewrite existing rooms/messages.

create table if not exists public.room_invitations (
    id bigint generated by default as identity primary key,
    room_name text not null,
    inviter_username text not null,
    invitee_username text not null,
    status text not null default 'pending' check (status in ('pending','accepted','declined','cancelled')),
    created_at timestamptz not null default now(),
    responded_at timestamptz
);

create index if not exists room_invitations_invitee_status_idx
    on public.room_invitations (invitee_username, status, created_at desc);
create index if not exists room_invitations_inviter_idx
    on public.room_invitations (inviter_username, created_at desc);

alter table public.room_invitations enable row level security;

-- A profile's owner_id is the authenticated Supabase user id.
drop policy if exists room_invitations_select on public.room_invitations;
create policy room_invitations_select on public.room_invitations
for select to authenticated
using (
    exists (
        select 1 from public.profiles p
        where p.owner_id = auth.uid()
          and (p.username = room_invitations.invitee_username
               or p.username = room_invitations.inviter_username)
    )
);

drop policy if exists room_invitations_insert on public.room_invitations;
create policy room_invitations_insert on public.room_invitations
for insert to authenticated
with check (
    exists (
        select 1 from public.profiles p
        where p.owner_id = auth.uid()
          and p.username = room_invitations.inviter_username
    )
    and inviter_username <> invitee_username
    and status = 'pending'
);

drop policy if exists room_invitations_update on public.room_invitations;
create policy room_invitations_update on public.room_invitations
for update to authenticated
using (
    exists (
        select 1 from public.profiles p
        where p.owner_id = auth.uid()
          and p.username = room_invitations.invitee_username
    )
)
with check (
    status in ('accepted','declined')
);

-- Realtime is optional; this is safe if the table is already in the publication.
do $$
begin
    alter publication supabase_realtime add table public.room_invitations;
exception
    when duplicate_object then null;
end $$;
