-- Table to store FCM tokens for users to receive push notifications
CREATE TABLE IF NOT EXISTS public.user_fcm_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    username TEXT NOT NULL,
    fcm_token TEXT NOT NULL UNIQUE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_user_fcm_tokens_username ON public.user_fcm_tokens (LOWER(username));
CREATE INDEX IF NOT EXISTS idx_user_fcm_tokens_user_id ON public.user_fcm_tokens (user_id);

ALTER TABLE public.user_fcm_tokens ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if any
DROP POLICY IF EXISTS "Users can manage their own fcm tokens" ON public.user_fcm_tokens;
DROP POLICY IF EXISTS "Service role full access on fcm tokens" ON public.user_fcm_tokens;

-- Allow authenticated users to view, insert, update their own tokens
CREATE POLICY "Users can manage their own fcm tokens"
ON public.user_fcm_tokens
FOR ALL
TO authenticated
USING (user_id = auth.uid() OR LOWER(username) = LOWER(COALESCE(auth.jwt()->>'username', '')))
WITH CHECK (user_id = auth.uid() OR LOWER(username) = LOWER(COALESCE(auth.jwt()->>'username', '')));

-- Allow service role full access (for Edge Functions)
CREATE POLICY "Service role full access on fcm tokens"
ON public.user_fcm_tokens
FOR ALL
TO service_role
USING (true)
WITH CHECK (true);
